"""Artifacts the app or the figures depend on must survive `git clone`.

Two real gaps this guards, both found the same way — by asking "would this work in a fresh
clone?" rather than "does it work here?":

  * results/rop/screening_rebase.json is read at RUNTIME by webapp/inference.py for the
    screening threshold. It was gitignored. A clone would have loaded no threshold, silently
    fallen back to the retired ResNet50 head, and served the model an external audit had just
    disqualified — with no error anywhere.
  * Figure 04 originally read preds_weights_test.npz, which carries 1,502 patient-pattern
    filenames and is gitignored for exactly that reason. The figure the whole re-basing rests
    on could not be regenerated by anyone. Fixed by deriving a de-identified companion
    (scores and labels only) rather than by loosening the PHI rule.

Run:  .venv/bin/python -m pytest tests/test_artifacts_are_committable.py -v
"""
import re
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

PHI = re.compile(rb"\d+_[MF]_GA\d+_BW\d+")


def _tracked_or_trackable(path: Path) -> bool:
    """True if git would keep this file — already tracked, or not ignored."""
    rel = str(path.relative_to(ROOT))
    if subprocess.run(["git", "ls-files", "--error-unmatch", rel], cwd=ROOT,
                      capture_output=True).returncode == 0:
        return True
    return subprocess.run(["git", "check-ignore", "-q", rel], cwd=ROOT,
                          capture_output=True).returncode != 0


# ── runtime dependencies ─────────────────────────────────────────────────────
RUNTIME = [
    "results/rop/screening_rebase.json",     # the served decision threshold
    "results/rop/operating_point.json",
    "results/rop/calibration_serving.json",
    "results/rop/abstention_band.json",
    "results/rop/gate_embedding.npz",        # third gradability layer
    "results/gate_thresholds.json",
    "webapp/registry.yaml",
]


@pytest.mark.parametrize("rel", RUNTIME)
def test_runtime_artifact_survives_a_clone(rel):
    p = ROOT / rel
    if not p.exists():
        pytest.skip(f"{rel} not present in this working tree")
    assert _tracked_or_trackable(p), (
        f"{rel} is gitignored but the app reads it at runtime — a fresh clone would "
        f"silently degrade rather than fail loudly")


def test_the_served_threshold_is_actually_readable():
    """Not just present: parseable, and the value the app will use."""
    import json
    p = ROOT / "results/rop/screening_rebase.json"
    if not p.exists():
        pytest.skip("re-basing artifact absent")
    d = json.loads(p.read_text())
    assert 0.0 < d["threshold"] < 1.0
    assert d["new_model"]["external_dev"]["specificity"] > 0.0, \
        "a served threshold with zero external specificity is the bug this file exists to fix"


# ── figure reproducibility ───────────────────────────────────────────────────
def test_every_figure_source_is_committable():
    """A figure whose input is gitignored is a figure nobody else can check."""
    src = (ROOT / "scripts" / "make_paper_figures.py").read_text()
    refs = set(re.findall(r'R / f?"([^"]+)"', src))
    missing = []
    for ref in sorted(refs):
        pat = ref.replace("{cell}", "structured_s42")
        hits = list((ROOT / "results" / "rop").glob(pat)) if "*" in pat or "[" in pat \
            else [ROOT / "results" / "rop" / pat]
        hits = [h for h in hits if h.is_file()]
        if not hits:
            continue                      # generated on demand; covered by the script itself
        for h in hits:
            if not _tracked_or_trackable(h):
                missing.append(str(h.relative_to(ROOT)))
    assert not missing, f"figure sources are gitignored: {missing}"


# ── the PHI rule this must never be 'fixed' by loosening ─────────────────────
def test_committable_result_files_carry_no_patient_identifiers():
    """The de-identified companion must stay de-identified, and its source must stay out."""
    raw = ROOT / "results/rop/preds_weights_test.npz"
    if raw.exists():
        assert not _tracked_or_trackable(raw), \
            "preds_weights_test.npz holds 1,502 patient-pattern filenames — it must stay ignored"
    for p in (ROOT / "results" / "rop").rglob("*"):
        if not p.is_file() or not _tracked_or_trackable(p):
            continue
        if PHI.search(p.read_bytes()):
            pytest.fail(f"{p.relative_to(ROOT)} is committable and contains a patient pattern")
